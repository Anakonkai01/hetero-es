#!/usr/bin/env python3
"""Offline, reproducible v2 threshold generator. Never imported by the runtime.

The two-precision check protects every floor operation. Decimal exp/sqrt are
used only here; sampling is an integer mapping with an immutable table.
"""

import argparse
from decimal import Decimal, localcontext
import hashlib
from pathlib import Path
import struct


def arctan_inverse(n):
    x = Decimal(1) / n
    power, total, k = x, x, 1
    while True:
        power *= -x * x
        term = power / (2 * k + 1)
        previous = total
        total += term
        if total == previous:
            return total
        k += 1


def half(bits):
    exponent, mantissa = bits >> 10, bits & 1023
    return (
        Decimal(mantissa) * Decimal(2) ** -24
        if exponent == 0
        else (Decimal(1024 + mantissa) * Decimal(2) ** (exponent - 25))
    )


def thresholds(precision):
    with localcontext() as ctx:
        ctx.prec = precision
        pi = 16 * arctan_inverse(5) - 4 * arctan_inverse(239)
        sqrt_pi, sqrt2 = pi.sqrt(), Decimal(2).sqrt()
        cutoff = Decimal(10) ** (-precision + 6)
        result = []
        while True:
            i = len(result)
            x = (half(i) + half(i + 1)) / 2 / sqrt2
            term, total, k, x2 = x, x, 0, x * x
            while True:
                k += 1
                term = term * 2 * x2 / (2 * k + 1)
                total += term
                if term < total * cutoff:
                    break
            erf = 2 / sqrt_pi * (-x2).exp() * total
            threshold = int(erf * 2**31)
            result.append(threshold)
            if threshold >= 2**31 - 1:
                return tuple(result)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    low, high = thresholds(60), thresholds(90)
    if low != high:
        raise RuntimeError("Threshold floors differ between Decimal precisions")
    digest = hashlib.sha256(struct.pack(f"<{len(low)}I", *low)).hexdigest()
    lines = [
        '"""Generated by scripts/gen-noise-v2-table.py; do not edit or format."""',
        "",
        f'TABLE_SHA256 = "{digest}"',
        "# fmt: off",
        "THRESHOLDS = (",
    ]
    lines += ["    " + ", ".join(map(str, low[i : i + 8])) + "," for i in range(0, len(low), 8)]
    lines += [")", "# fmt: on", ""]
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(low)} thresholds; Decimal 60 == 90; sha256={digest}")


if __name__ == "__main__":
    main()
