#!/usr/bin/env python3
"""Generate docs/EVIDENCE-INDEX.md from the `evidence-archive` branch (evidence is kept there, not on main).

    python3 scripts/build-evidence-index.py            # rewrite docs/EVIDENCE-INDEX.md
    python3 scripts/build-evidence-index.py --check    # exit 1 when the file is not what the branch gives

One line per folder of docs/evidence, runtime/artifacts/<group> and docs/archive: the README title when the folder has
one, otherwise "(no README)" and its file count. Reads git objects only; the working tree is never touched.
"""

import argparse
import subprocess
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs/EVIDENCE-INDEX.md"
BRANCH = "evidence-archive"
SECTIONS = [  # (heading, prefix)
    ("Evidence folders (`docs/evidence/`)", "docs/evidence/"),
    ("Runtime artifacts (`runtime/artifacts/`)", "runtime/artifacts/"),
    ("Older session records (`docs/archive/`)", "docs/archive/"),
]
GROUPS = {"experiments", "probes", "regression"}  # runtime/artifacts/<group>/<folder>


def git(*args):
    return subprocess.run(["git", "-C", str(REPO), *args], check=True, capture_output=True, text=True).stdout


def title(path):
    for line in git("show", f"{BRANCH}:{path}").splitlines():
        if line.startswith("# "):
            return line[2:].strip().replace("|", "\\|")
    return "(README without a title)"


def render():
    commit = git("rev-parse", BRANCH).strip()
    files = git("ls-tree", "-r", "--name-only", BRANCH).splitlines()
    lines = [
        "# Evidence index",
        "",
        f"Generated by `scripts/build-evidence-index.py` from branch `{BRANCH}` (commit `{commit[:12]}`); do not edit by",
        "hand. The evidence moved off `main` on 2026-10-28 byte-identically (same git blobs, same paths) and is read with",
        f"`git show {BRANCH}:<path>` or a worktree: `git worktree add ../heteroes-evidence {BRANCH}`.",
    ]
    for heading, prefix in SECTIONS:
        counts = Counter()
        readmes = {}
        for f in files:
            if not f.startswith(prefix):
                continue
            parts = f[len(prefix) :].split("/")
            depth = 2 if parts[0] in GROUPS else 1
            if len(parts) <= depth:  # a loose file directly in the section
                folder, rest = "/".join(parts), []
            else:
                folder, rest = "/".join(parts[:depth]), parts[depth:]
            counts[folder] += 1
            if rest == ["README.md"]:
                readmes[folder] = f
        lines += ["", f"## {heading}", "", "| Folder | Files | Title |", "| --- | ---: | --- |"]
        for folder in sorted(counts):
            label = title(readmes[folder]) if folder in readmes else "(no README)"
            lines.append(f"| `{folder}` | {counts[folder]} | {label} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(REPO)} is out of date: run scripts/build-evidence-index.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
