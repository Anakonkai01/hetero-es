CREATE TABLE IF NOT EXISTS assignment_members (change_id TEXT PRIMARY KEY,run_id TEXT NOT NULL,worker_id TEXT NOT NULL,device_id TEXT NOT NULL,action TEXT NOT NULL CHECK(action IN ('JOIN','LEAVE')),actor TEXT NOT NULL,created DOUBLE PRECISION NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS assignments(id TEXT PRIMARY KEY,run_id TEXT NOT NULL,coordinator TEXT NOT NULL,
                        epoch BIGINT NOT NULL,body TEXT NOT NULL,snapshot TEXT NOT NULL,released BIGINT NOT NULL DEFAULT 0, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS audit (sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor TEXT, action TEXT, target TEXT, created TEXT, workspace_id TEXT);

CREATE TABLE IF NOT EXISTS cloud_downloads(digest TEXT PRIMARY KEY,user_id TEXT NOT NULL,session_digest TEXT NOT NULL,run_id TEXT NOT NULL,sha TEXT NOT NULL,expires DOUBLE PRECISION NOT NULL);

CREATE TABLE IF NOT EXISTS cloud_objects(sha TEXT PRIMARY KEY,size BIGINT NOT NULL,status TEXT NOT NULL,upload_plan TEXT,expires DOUBLE PRECISION);

CREATE TABLE IF NOT EXISTS cloud_refs(point_id TEXT NOT NULL,sha TEXT NOT NULL,PRIMARY KEY(point_id,sha));

CREATE TABLE IF NOT EXISTS cloud_requests(month TEXT PRIMARY KEY,class_a BIGINT NOT NULL,class_b BIGINT NOT NULL);

CREATE TABLE IF NOT EXISTS device_commands (id TEXT PRIMARY KEY,device_id TEXT NOT NULL,dedupe TEXT NOT NULL UNIQUE,body TEXT NOT NULL,ack BIGINT NOT NULL DEFAULT 0,created DOUBLE PRECISION NOT NULL);

CREATE TABLE IF NOT EXISTS device_reports (device_id TEXT NOT NULL,assignment_id TEXT NOT NULL,sequence BIGINT NOT NULL,PRIMARY KEY(device_id,assignment_id,sequence));

CREATE TABLE IF NOT EXISTS device_reservations (device_id TEXT PRIMARY KEY,assignment_id TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS device_telemetry_history(device_id TEXT NOT NULL,boot_id TEXT NOT NULL,sampled_at DOUBLE PRECISION NOT NULL,received_at DOUBLE PRECISION NOT NULL,body TEXT NOT NULL,PRIMARY KEY(device_id,boot_id,sampled_at));

CREATE TABLE IF NOT EXISTS devices (id TEXT PRIMARY KEY,worker_id TEXT UNIQUE NOT NULL,owner TEXT NOT NULL,name TEXT NOT NULL,token_digest TEXT NOT NULL,status TEXT NOT NULL,compute_url TEXT NOT NULL,self_test TEXT NOT NULL,boot_id TEXT,seen DOUBLE PRECISION NOT NULL DEFAULT 0,enabled BIGINT NOT NULL DEFAULT 0,desired BIGINT NOT NULL DEFAULT 0,processes TEXT NOT NULL DEFAULT '[]', telemetry TEXT, bulk_url TEXT, keep_on BIGINT NOT NULL DEFAULT 0, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS experiment_templates (id TEXT PRIMARY KEY, workspace_id TEXT NOT NULL, owner_id TEXT NOT NULL, name TEXT NOT NULL, config TEXT NOT NULL, created TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS experiments (id TEXT PRIMARY KEY, owner TEXT NOT NULL, body TEXT NOT NULL, snapshot TEXT, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS invitations(id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL,user_id TEXT NOT NULL,status TEXT NOT NULL,created TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS join_requests(id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL,user_id TEXT NOT NULL,
            status TEXT NOT NULL,created TEXT NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS memberships(workspace_id TEXT NOT NULL,user_id TEXT NOT NULL,role TEXT NOT NULL CHECK(role IN ('ADMIN','PARTICIPANT')),PRIMARY KEY(workspace_id,user_id));

CREATE TABLE IF NOT EXISTS model_engine_qualifications(device_id TEXT NOT NULL,workspace_id TEXT NOT NULL,
            manifest_hash TEXT NOT NULL,profile_hash TEXT NOT NULL,reference_hash TEXT NOT NULL,body TEXT NOT NULL,
            engine TEXT NOT NULL,PRIMARY KEY(device_id,workspace_id,manifest_hash,engine));

CREATE TABLE IF NOT EXISTS model_engine_references(workspace_id TEXT NOT NULL,manifest_hash TEXT NOT NULL,
            reference_hash TEXT NOT NULL,body TEXT NOT NULL,engine TEXT NOT NULL,
            PRIMARY KEY(workspace_id,manifest_hash,engine));

CREATE TABLE IF NOT EXISTS model_probe_jobs(id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL,asset_id TEXT NOT NULL,
            device_id TEXT NOT NULL,body TEXT NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS model_probe_reservations(job_id TEXT PRIMARY KEY,device_id TEXT UNIQUE NOT NULL,
            resource_id TEXT UNIQUE NOT NULL);

CREATE TABLE IF NOT EXISTS model_qualifications(device_id TEXT NOT NULL,workspace_id TEXT NOT NULL,
            manifest_hash TEXT NOT NULL,profile_hash TEXT NOT NULL,reference_hash TEXT NOT NULL,body TEXT NOT NULL,
            PRIMARY KEY(device_id,workspace_id,manifest_hash));

CREATE TABLE IF NOT EXISTS model_references(workspace_id TEXT NOT NULL,manifest_hash TEXT NOT NULL,
            reference_hash TEXT NOT NULL,body TEXT NOT NULL,PRIMARY KEY(workspace_id,manifest_hash));

CREATE TABLE IF NOT EXISTS monitoring_events(sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_id TEXT UNIQUE NOT NULL,assignment_id TEXT NOT NULL,body TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS notifications (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id TEXT NOT NULL, kind TEXT NOT NULL, params TEXT NOT NULL, target TEXT NOT NULL, created TEXT NOT NULL, read_at TEXT, dedupe TEXT NOT NULL UNIQUE);

CREATE TABLE IF NOT EXISTS pairing_codes (digest TEXT PRIMARY KEY,owner TEXT NOT NULL,expires DOUBLE PRECISION NOT NULL,used BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS physical_reservations (resource_id TEXT PRIMARY KEY,assignment_id TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS queue (sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, run_id TEXT NOT NULL UNIQUE);

CREATE TABLE IF NOT EXISTS recovery_points(id TEXT PRIMARY KEY,run_id TEXT NOT NULL,generation BIGINT NOT NULL,final BIGINT NOT NULL,status TEXT NOT NULL,manifest TEXT NOT NULL,error TEXT,created DOUBLE PRECISION NOT NULL);

CREATE TABLE IF NOT EXISTS sessions (digest TEXT PRIMARY KEY, user_id TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL);

CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS study_assets(id TEXT PRIMARY KEY,workspace_id TEXT NOT NULL,owner TEXT NOT NULL,kind TEXT NOT NULL,body TEXT NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS study_uploads(id TEXT PRIMARY KEY,asset_id TEXT NOT NULL,name TEXT NOT NULL,object_sha TEXT NOT NULL,upload_key TEXT NOT NULL,size BIGINT NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, hash TEXT NOT NULL, profile TEXT NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE TABLE IF NOT EXISTS worker_assignments(worker_id TEXT PRIMARY KEY,owner TEXT NOT NULL,workspace_id TEXT);

CREATE TABLE IF NOT EXISTS workspace_settings(workspace_id TEXT PRIMARY KEY,body TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS workspaces(id TEXT PRIMARY KEY,name TEXT NOT NULL,description TEXT NOT NULL,creator TEXT NOT NULL, _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL);

CREATE UNIQUE INDEX IF NOT EXISTS active_assignment_per_run ON assignments(run_id) WHERE released=0;

CREATE UNIQUE INDEX IF NOT EXISTS assignment_epoch ON assignments(run_id,epoch);

CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id, id);

CREATE UNIQUE INDEX IF NOT EXISTS pending_invitation ON invitations(workspace_id,user_id) WHERE status='PENDING';

CREATE UNIQUE INDEX IF NOT EXISTS pending_join_request ON join_requests(workspace_id,user_id)
            WHERE status='PENDING';

CREATE UNIQUE INDEX IF NOT EXISTS username ON users((profile::jsonb->>'username'));

CREATE TABLE IF NOT EXISTS schema_versions(version BIGINT PRIMARY KEY, applied TEXT NOT NULL);
