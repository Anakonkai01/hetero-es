"""One-time source conversion of the immutable B1 SQLite schema, not a runtime SQL translator."""
import json,re
from pathlib import Path
baseline=json.loads(Path('.scratch/review-2026-11/B1/schema-before.json').read_text())
ordered={'users','devices','assignments','assignment_members','study_assets','study_uploads','workspaces','join_requests','experiments','model_probe_jobs'}
parts=['-- PostgreSQL 17 product schema. Integer/real fields retain SQLite 64-bit/double semantics.\n-- Keep changes additive and mirror logical columns/constraints in migrations.py.']
for item in baseline['catalog']:
 if item['type']!='table':continue
 sql=item['sql']
 sql=re.sub(r'\bINTEGER PRIMARY KEY AUTOINCREMENT\b','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql)
 sql=re.sub(r'\bINTEGER\b','BIGINT',sql)
 sql=re.sub(r'\bREAL\b','DOUBLE PRECISION',sql)
 sql=re.sub(r'"([^"\n]*)"',lambda m:"'"+m[1].replace("'","''")+"'",sql)
 sql=sql.replace('CREATE TABLE ','CREATE TABLE IF NOT EXISTS ',1)
 if item['name'] in ordered:
  sql=sql.rstrip()[:-1]+', _insert_order BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL)'
 parts.append(sql+';')
for item in baseline['catalog']:
 if item['type']!='index':continue
 sql=item['sql'].replace('CREATE UNIQUE INDEX ','CREATE UNIQUE INDEX IF NOT EXISTS ',1).replace('CREATE INDEX ','CREATE INDEX IF NOT EXISTS ',1)
 sql=sql.replace("json_extract(profile,'$.username')","(profile::jsonb->>'username')")
 sql=sql.replace('"PENDING"',"'PENDING'")
 parts.append(sql+';')
parts.append('CREATE TABLE IF NOT EXISTS schema_versions(version BIGINT PRIMARY KEY, applied TEXT NOT NULL);')
Path('backend/db/postgres_schema.sql').write_text('\n\n'.join(parts)+'\n')
print('Generated 37 tables, six indexes, ten insertion-order identities and the version table')
